#!/usr/bin/env python3
"""Regenerate src/BuilderIcons/Names.luau from the Builder Icons package that ships with Studio.

    python3 scripts/generate-builder-icons.py [path/to/BuilderIcons/Icon.lua]

Without a path it looks in the newest Studio install (Vinegar on Linux, then Windows).
Run it after a Studio update to pick up new icons, then commit the result.
"""
import glob
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "src", "BuilderIcons", "Names.luau")
SUFFIX = "ExtraContent/LuaPackages/Packages/_Index/BuilderIcons/BuilderIcons/Icon.lua"
ENTRY = re.compile(r'\["([^"]+)"\]\s*=\s*"([^"]+)"')


def find_icon_file():
    home = os.path.expanduser("~")
    patterns = [
        f"{home}/.var/app/org.vinegarhq.Vinegar/data/vinegar/versions/*/{SUFFIX}",
        f"{os.environ.get('XDG_DATA_HOME', home + '/.local/share')}/vinegar/versions/*/{SUFFIX}",
    ]
    if os.environ.get("LOCALAPPDATA"):
        patterns.append(f"{os.environ['LOCALAPPDATA']}/Roblox/Versions/*/{SUFFIX}")
    for pattern in patterns:
        matches = sorted(glob.glob(pattern), key=os.path.getmtime, reverse=True)
        if matches:
            return matches[0]
    raise SystemExit("Could not find Studio's BuilderIcons/Icon.lua. Pass its path as an argument.")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else find_icon_file()
    names = sorted(set(ligature for _, ligature in ENTRY.findall(open(path).read())))
    if not names:
        raise SystemExit(f"No icons found in {path}")
    lines = [
        "-- @generated by scripts/generate-builder-icons.py from Studio's BuilderIcons package.",
        "-- Each name is a ligature: set it as Text with the Builder Icons font to draw the icon.",
        "return table.freeze({",
    ]
    lines += [f'\t"{name}",' for name in names]
    lines.append("})")
    with open(OUT, "w") as file:
        file.write("\n".join(lines) + "\n")
    print(f"Wrote {len(names)} icons to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
